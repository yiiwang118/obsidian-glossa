const path = require('path');
const fs = require('fs');
const vm = require('vm');
const ts = require('typescript');
exports.run = async (t, load) => {
  const rail = await load(path.resolve(__dirname, '../src/ui/thread_rail.ts'));
  const viewport = { top: 100, height: 600, scrollTop: 500, scrollHeight: 2000 };
  t.eq(rail.activeQuestionIndex([-1400, -900, -300], viewport), 2, 'all questions above viewport selects latest, not first');
  t.eq(rail.activeQuestionIndex([-600, 126, 900], viewport), 1, 'question crossing reading line owns the visible answer');
  t.eq(rail.activeQuestionIndex([-600, 170, 900], viewport), 0, 'upcoming question does not steal active state early');
  t.eq(rail.activeQuestionIndex([-600, 100, 600], { ...viewport, scrollTop: 1400 }), 2, 'scroll bottom selects last question even when several short turns fit');
  t.eq(rail.activeQuestionIndex([110, 300], { ...viewport, scrollTop: 0, scrollHeight: 500 }), 0, 'non-scrolling short chat starts at first question');
  t.eq(rail.activeQuestionIndex([], viewport), -1, 'empty rail has no active item');
  t.eq(rail.activeQuestionIndex([-1000, 900], viewport), 0, 'long answer retains its source question');
  t.eq(rail.activeQuestionIndex([-1000, 134], viewport), 1, 'layout changes can move the next question into view');
  const source = fs.readFileSync(path.resolve(__dirname, '../src/ui/view.ts'), 'utf8');
  const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const exports = {};
  vm.runInNewContext(code, { exports, console, require: name => name === 'obsidian' ? { ItemView: class {} } : name === './thread_rail' ? rail : {} });
  const view = Object.create(exports.GlossaView.prototype);
  view.messagesEl = { clientHeight: 600, scrollHeight: 2000, scrollTop: 1400, getBoundingClientRect: () => ({ top: 100 }) };
  view.railItems = [-1400, -1000, -300].map((top, i) => ({ id: `q${i}`, messageEl: { isConnected: true, getBoundingClientRect: () => ({ top, bottom: top + 20 }) } }));
  view.setActiveRailItem = id => { view.active = id; };
  view.updateActiveRailItem();
  t.eq(view.active, 'q2', 'real view applies last-question selection at the bottom');
  view.railItems[2].messageEl.isConnected = false;
  view.updateActiveRailItem();
  t.eq(view.active, 'q1', 'detached history rows never become active');
};
