const path = require('node:path');
exports.run = async (t, load) => {
  const { IdleCompactor, idleCompactDelay, cacheablePrefix, requestPromptTokens } = await load(path.resolve(__dirname, '../src/agent/idle_compaction.ts'));
  t.eq(requestPromptTokens({ input: 812, cacheRead: 148000, cacheWrite: 1500 }, 'anthropic'), 150312, 'Anthropic cached prompt tokens count toward the threshold');
  t.eq(requestPromptTokens({ input: 150000, cacheRead: 148000 }, 'openai'), 150000, 'OpenAI prompt tokens already include cached ones');
  t.eq(requestPromptTokens({ input: 150000, cacheRead: 148000 }, undefined), 150000, 'the default style is OpenAI-compatible');
  t.eq(requestPromptTokens(undefined, 'anthropic'), 0, 'a request without usage never qualifies');
  const { compactSession, applyCompact, undoCompact } = await load(path.resolve(__dirname, '../src/agent/compact.ts'));
  const opts = { enabled: true, api: true, cacheSeconds: 300, inputTokens: 100000, finishedAt: 0, now: 1000 };
  t.eq(idleCompactDelay(opts), 239000, 'five-minute cache scheduled in final 20 percent');
  t.eq(idleCompactDelay({ ...opts, cacheSeconds: 3600 }), 3479000, 'long window lead capped at two minutes');
  for (const change of [{ enabled: false }, { api: false }, { cacheSeconds: undefined }, { cacheSeconds: NaN }, { inputTokens: 99999 }, { now: 300000 }]) t.eq(idleCompactDelay({ ...opts, ...change }), null, 'unsupported or expired conditions skip');
  const timers = new Map(); let next = 0;
  const scheduler = new IdleCompactor({ set: fn => { timers.set(++next, fn); return next; }, clear: id => timers.delete(id) });
  const fire = async () => { const work = [...timers.values()]; timers.clear(); for (const fn of work) fn(); await new Promise(resolve => setTimeout(resolve, 0)); };
  let calls = 0, ready = false;
  const fail = e => { throw e; };
  scheduler.schedule('a', 10, () => true, async () => { calls++; }, fail);
  scheduler.cancel('a'); await fire(); t.eq(calls, 0, 'typing or submit cancels pending work');
  scheduler.schedule('a', 10, () => ready, async () => { calls++; }, fail);
  await fire(); t.eq(calls, 0, 'busy or queued state skips without rescheduling');
  scheduler.schedule('a', 10, () => true, async () => { calls++; }, fail);
  await fire(); await fire(); t.eq(calls, 1, 'one paid opportunity per turn');
  let signal, finish;
  scheduler.schedule('a', 10, () => true, async s => { signal = s; await new Promise(r => { finish = r; }); }, fail);
  await fire(); scheduler.cancel('a'); t.ok(signal.aborted, 'new message cancels in-flight inference'); finish();
  scheduler.schedule('b', 10, () => true, async () => { calls++; }, fail);
  scheduler.stop(); await fire(); t.eq(calls, 1, 'plugin unload clears all timers');
  const initial = { systemPrompt: 'Stable system', tools: [{ name: 'read_note', parameters: {}, description: 'Read' }], messages: [{ role: 'user', content: 'Original prefix' }], model: 'same-model' };
  const prefix = cacheablePrefix(initial, { role: 'assistant', content: 'Answer' });
  initial.messages[0].content = 'Later mutation';
  t.eq(prefix.messages[0].content, 'Original prefix', 'cache prefix is a detached snapshot');
  t.eq(cacheablePrefix({ ...initial, attachedImages: [{ dataUri: 'data:image/png;base64,a' }] }, { role: 'assistant', content: '' }), undefined, 'images bound to latest user cannot be relocated by summary');
  t.eq(cacheablePrefix({ ...initial, messages: [{ role: 'user', content: 'x'.repeat(2000001) }] }, { role: 'assistant', content: '' }), undefined, 'idle request memory is bounded');
  const chat = { id: 'chat', messages: Array.from({ length: 6 }, (_, i) => ({ id: `m${i}`, role: i % 2 ? 'assistant' : 'user', content: `Text ${i}`, timestamp: i })) };
  let sent;
  const provider = { async *stream(req) { sent = req; yield { type: 'final', text: 'Summary' }; } };
  const compacted = await compactSession(chat, { provider, cachePrefix: prefix });
  t.eq(sent.systemPrompt, prefix.systemPrompt, 'cached system prompt stays unchanged');
  t.eq(sent.tools, prefix.tools, 'tool prefix retained for possible cache reuse');
  t.eq(sent.messages.slice(0, -1), prefix.messages, 'all previous model-facing messages retained in order');
  t.ok(sent.messages.at(-1).content.includes('do not use tools'), 'summary request appended without changing prefix');
  chat.messages[0].content = 'User edited during summary';
  t.throws(() => applyCompact(chat, compacted, 2), 'stale summary cannot discard a concurrent edit');
  t.eq(chat.messages.length, 6, 'stale result leaves full history intact');
  const fresh = await compactSession(chat, { provider, cachePrefix: prefix });
  applyCompact(chat, fresh, 2);
  t.eq(chat.messages.length, 3, 'valid result applies with recent tail retained');
  t.ok(undoCompact(chat, fresh.summaryMsg.id), 'idle summary uses existing undo snapshots');
  t.eq(chat.messages[0].content, 'User edited during summary', 'undo restores exact original evidence');
  const controller = new AbortController();
  const late = { async *stream() { controller.abort(); yield { type: 'final', text: 'Late summary' }; } };
  let aborted = false;
  try { await compactSession(chat, { provider: late, signal: controller.signal }); } catch { aborted = true; }
  t.ok(aborted, 'aborted provider output never applies');
  const toolProvider = { async *stream() { yield { type: 'tool_call', id: 'x', name: 'write_note', args: {} }; } };
  let rejected = false;
  try { await compactSession(chat, { provider: toolProvider, cachePrefix: prefix }); } catch { rejected = true; }
  t.ok(rejected, 'summary tool requests fail without executing anything');
  const cli = { async *stream() { yield { type: 'tool_event', id: 'ls', name: 'cli_command_execution', args: {}, status: 'success' }; yield { type: 'text', text: 'CLI summary' }; yield { type: 'final', text: '' }; } };
  t.eq((await compactSession(chat, { provider: cli })).summaryMsg.content, 'CLI summary', 'a CLI that already ran a read-only tool still yields its summary');
};
